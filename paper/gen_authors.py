"""
Generate paper/authors.typ from the author and affiliation blocks in the Overleaf main.tex.

Usage: uv run paper/gen_authors.py path/to/overleaf/main.tex
"""

import re
import sys
from pathlib import Path

OUT_PATH = Path(__file__).with_name("authors.typ")

AUTHOR_RE = re.compile(
    r"^\s*(?:and\s+)?(?P<name>.+?)(?:\\,\\pmgORCID\{(?P<orcid>[\dX-]+)\})?"
    r"\\textit\{\$\^\{(?P<marks>[^}]*)\}\$\}",
    re.MULTILINE,
)
AFFILIATION_RE = re.compile(
    r"^\s*\{\\footnotesize\\textit\{\$\^\{([a-z]+)\}\$\} (.+?)\}\s*$", re.MULTILINE
)


def tex_to_text(text: str) -> str:
    """Undo the LaTeX escapes used in names and affiliations; fail on any other TeX."""
    text = text.replace(r"\&", "&").strip()
    if "\\" in text:
        raise ValueError(f"unhandled TeX in {text!r}")
    return text


def typ_str(text: str) -> str:
    """Quote a Python string as a Typst string literal."""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def author_marks(match: re.Match[str]) -> list[str]:
    """Superscript marks of an AUTHOR_RE match: affiliation keys, \\dagger, \\ast."""
    return [mark.strip() for mark in match["marks"].split(",")]


def author_line(match: re.Match[str]) -> str:
    """Typst dictionary for one author from an AUTHOR_RE match."""
    marks = author_marks(match)
    aff_keys = [mark for mark in marks if mark.isalpha()]
    fields = [f"name: {typ_str(tex_to_text(match['name']))}"]
    if match["orcid"]:
        fields.append(f"orcid: {typ_str(match['orcid'])}")
    fields.append("affiliations: (" + ", ".join(map(typ_str, aff_keys)) + ",)")
    if r"\dagger" in marks:
        fields.append("equal-contrib: true")
    if r"\ast" in marks:
        fields.append("corresponding: true")
    return f"  ({', '.join(fields)}),"


def main(tex_path: str) -> None:
    tex = Path(tex_path).read_text(encoding="utf-8")
    author_block = tex.split("BEGIN GENERATED AUTHOR CELL")[1].split(
        "END GENERATED AUTHOR CELL"
    )[0]
    authors = list(AUTHOR_RE.finditer(author_block))
    affiliations = AFFILIATION_RE.findall(tex)
    if len(authors) != (n_marks := author_block.count(r"\textit{$^{")):
        raise ValueError(f"parsed {len(authors)} of {n_marks} authors")

    used_keys = {mark for match in authors for mark in author_marks(match)}
    used_keys -= {r"\dagger", r"\ast"}
    defined_keys = {key for key, _ in affiliations}
    if len(defined_keys) != len(affiliations):
        raise ValueError("duplicate affiliation keys")
    if missing := used_keys - defined_keys:
        raise ValueError(f"authors reference undefined affiliations: {sorted(missing)}")
    if unused := defined_keys - used_keys:
        raise ValueError(f"affiliations not used by any author: {sorted(unused)}")

    lines = [
        "// Generated by paper/gen_authors.py from the Overleaf main.tex. Edit there, then regenerate.",
        "#let authors = (",
        *map(author_line, authors),
        ")",
        "",
        "#let affiliations = (",
        *(
            f"  (key: {typ_str(key)}, label: {typ_str(key)}, affiliation: {typ_str(tex_to_text(text))}),"
            for key, text in affiliations
        ),
        ")",
    ]
    OUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(
        f"Wrote {len(authors)} authors and {len(affiliations)} affiliations to {OUT_PATH}"
    )


if __name__ == "__main__":
    main(*sys.argv[1:])
